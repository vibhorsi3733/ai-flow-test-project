"""Measured Claude usage of one package -> per-stage table + the MEASURED section of expense.txt.

    python -m motion_ai.expense output/<package>.json            # print table, rewrite expense.txt
    python -m motion_ai.expense output/<package>.json --no-write # print only

Reads the manifest's `llm_usage` (written by HighlightPipeline / replay, see motion_ai.llm). The block between
the MEASURED markers at the top of expense.txt is replaced on every run; the estimate sections below it are
kept as they are. Running it twice on the same package gives the same file.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from .llm import TOKEN_KEYS

BEGIN = "=== BEGIN MEASURED (generated by python -m motion_ai.expense; do not edit by hand) ==="
END = "=== END MEASURED ==="
EXPENSE_FILE = Path("expense.txt")


def _n(v) -> str:
    return "-" if v is None else f"{v:,}"


def _usd(v) -> str:
    return "-" if v is None else f"${v:.4f}"


def table(usage: dict) -> str:
    """Per-stage rows: calls, input, output, cache read, cache write, cost."""
    head = f"{'Stage':<12}{'Calls':>6}{'OK':>5}{'Input':>11}{'Output':>11}{'Cache read':>12}{'Cache write':>13}{'Cost':>11}"
    rows = [head, "-" * len(head)]

    def row(name: str, a: dict) -> str:
        cost = _usd(a.get("cost_usd")) + ("" if a.get("cost_complete", True) else "*")
        return (f"{name:<12}{a.get('calls', 0):>6}{a.get('ok', 0):>5}{_n(a.get('input_tokens')):>11}"
                f"{_n(a.get('output_tokens')):>11}{_n(a.get('cache_read_input_tokens')):>12}"
                f"{_n(a.get('cache_creation_input_tokens')):>13}{cost:>11}")

    for name, a in sorted((usage.get("stages") or {}).items()):
        rows.append(row(name, a))
    rows.append("-" * len(head))
    rows.append(row("TOTAL", usage.get("total") or {k: 0 for k in TOKEN_KEYS}))
    return "\n".join(rows)


def measured_section(usage: dict, package_name: str) -> str:
    total = usage.get("total") or {}
    lines = [BEGIN,
             f"MEASURED (from {package_name})",
             f"Run: {usage.get('run', 'unknown')}   Backend: {usage.get('backend')}   "
             f"Models: {', '.join(usage.get('models') or []) or '-'}",
             f"Cost basis: {usage.get('cost_basis') or '-'}",
             "",
             table(usage),
             ""]
    if total.get("calls_without_usage"):
        lines.append(f"{total['calls_without_usage']} call(s) returned no usage (failed before a response): "
                     "tokens not counted, not estimated.")
    if not total.get("cost_complete", True):
        lines.append("* cost incomplete: some calls used a model that is not in the price table.")
    if "cli_reported_cost_usd" in total:
        lines.append(f"Claude CLI's own total_cost_usd (list price, incl. its helper-model calls): "
                     f"{_usd(total['cli_reported_cost_usd'])}")
    if usage.get("note"):
        lines.append(f"NOTE: {usage['note']}")
    for n in usage.get("price_notes") or []:
        lines.append(f"Price note: {n}")
    lines.append(f"Latency (sum of call times): {total.get('latency_s', 0)} s")
    lines.append(END)
    return "\n".join(lines) + "\n"


def rewrite(text: str, section: str) -> str:
    """Replace the MEASURED block (or put it on top) and keep everything else."""
    if BEGIN in text and END in text:
        before, rest = text.split(BEGIN, 1)
        after = rest.split(END, 1)[1].lstrip("\n")
        return before + section + "\n" + after
    return section + "\n" + text


def load_usage(package: Path) -> dict:
    manifest = json.loads(package.read_text())
    usage = manifest.get("llm_usage")
    if not isinstance(usage, dict):
        raise SystemExit(f"{package}: no llm_usage in the manifest (package built before usage logging?)")
    return usage


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("package", type=Path)
    ap.add_argument("--expense-file", type=Path, default=EXPENSE_FILE)
    ap.add_argument("--no-write", action="store_true")
    args = ap.parse_args(argv)
    usage = load_usage(args.package)
    section = measured_section(usage, args.package.name)
    sys.stdout.write(section)
    if not args.no_write:
        old = args.expense_file.read_text() if args.expense_file.exists() else ""
        args.expense_file.write_text(rewrite(old, section))
        print(f"updated {args.expense_file}")


if __name__ == "__main__":
    main()
